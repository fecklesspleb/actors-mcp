// Regenerate src/snapshots.ts from the Actors' current default builds on Apify.
// Usage: node scripts/snapshot-schemas.mjs
import { readFileSync, writeFileSync } from "node:fs";

const catalog = readFileSync(new URL("../src/catalog.ts", import.meta.url), "utf8");
const actors = [...catalog.matchAll(/actor: "([^"]+)"/g)].map((m) => m[1]);
const out = {};
const meta = {};
for (const actor of actors) {
  const res = await fetch(`https://api.apify.com/v2/acts/${actor.replace("/", "~")}/builds/default`);
  if (!res.ok) throw new Error(`${actor}: HTTP ${res.status}`);
  const { data } = await res.json();
  out[actor] = JSON.parse(data.inputSchema);
  meta[actor] = { build: data.buildNumber, finishedAt: data.finishedAt };
}
const body =
  "// Generated by scripts/snapshot-schemas.mjs. Do not edit by hand.\n" +
  "// Fallback input schemas, used only when the live schema cannot be fetched.\n" +
  `// Builds: ${JSON.stringify(meta)}\n` +
  'import type { ApifyInputSchema } from "./schema.js";\n\n' +
  `export const SNAPSHOTS: Record<string, ApifyInputSchema> = ${JSON.stringify(out, null, 2)};\n`;
writeFileSync(new URL("../src/snapshots.ts", import.meta.url), body);
console.log(`Wrote ${actors.length} schemas.`);
